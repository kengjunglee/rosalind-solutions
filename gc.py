def parse_fasta(fasta: str) -> dict[str, str]:
    """
    Parse a FASTA-formatted string into a dictionary of sequences.

    Args:
        fasta: A string in FASTA format, where each record begins with a '>'
            line followed by one or more lines of sequence data.

    Returns:
        A dictionary mapping sequence IDs to their concatenated sequences.
    """
    sequences: dict[str, str] = {}
    current_id: str = ""
    for line in fasta.strip().split("\n"):
        if line.startswith(">"):
            current_id = line[1:].strip()
            sequences[current_id] = ""
        else:
            sequences[current_id] += line.strip()
    return sequences

